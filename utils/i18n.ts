export type Language = 'en' | 'es';
export type Translate = (key: string, values?: Record<string, string | number | undefined>) => string;

/** Solo español e inglés: los idiomas no compatibles usan inglés como alternativa. */
export function resolveLanguage(preference: 'system' | Language, languageCodes: (string | null)[]): Language {
  if (preference !== 'system') return preference;
  const supported = languageCodes.find(code => code?.match(/^(es|en)(-|$)/i));
  return supported?.toLowerCase().startsWith('es') ? 'es' : 'en';
}

/** Sustituye parámetros sin modificar nombres, lotes ni otros datos del reporte. */
export function createTranslator(language: Language): Translate {
  return (key, values = {}) => {
    const spanish: Record<string, string> = { 'OVERALL APPEARANCE': 'APARIENCIA GENERAL', 'MEASURES': 'MEDIDAS', 'Overall appearance': 'Apariencia general', 'Measures': 'Medidas', 'MODELS': 'MODELOS', 'QUANTITIES': 'CANTIDADES', 'PRODUCTION REPORT WH MATTRESS PANAMA': 'REPORTE DE PRODUCCIÓN WH MATTRESS PANAMA' };
    const text = language === 'en' ? english[key as keyof typeof english] ?? key : spanish[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
  };
}

/** Conserva la clave de un error para poder traducirlo de nuevo si cambia el idioma. */
export class LocalizedError extends Error {
  constructor(readonly key: string, readonly values: Record<string, string | number> = {}, t: Translate = createTranslator('es')) {
    super(t(key, values));
  }
  localize(t: Translate) { return t(this.key, this.values); }
}
